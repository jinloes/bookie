UPDATE incomes i
SET activity_id = (
    SELECT fa.id
    FROM financial_activities fa
    WHERE fa.property_id = i.property_id
)
WHERE i.property_id IS NOT NULL;

UPDATE expenses e
SET activity_id = (
    SELECT fa.id
    FROM financial_activities fa
    WHERE fa.property_id = e.property_id
)
WHERE e.property_id IS NOT NULL;

UPDATE pending_incomes pi
SET activity_id = (
    SELECT fa.id
    FROM financial_activities fa
    WHERE fa.property_id = pi.property_id
)
WHERE pi.property_id IS NOT NULL;

UPDATE pending_expenses pe
SET activity_id = (
    SELECT MIN(fa.id)
    FROM financial_activities fa
    JOIN properties p ON p.id = fa.property_id
    WHERE LOWER(p.name) = LOWER(pe.property_name)
)
WHERE pe.property_name IS NOT NULL;

