CREATE TABLE household_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    system_key VARCHAR(100),
    CONSTRAINT uk_household_members_name UNIQUE (name),
    CONSTRAINT uk_household_members_system_key UNIQUE (system_key)
);

INSERT INTO household_members (name, active, system_key)
VALUES ('Household', TRUE, 'DEFAULT_HOUSEHOLD');

CREATE TABLE financial_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    activity_type VARCHAR(50) NOT NULL,
    tax_treatment VARCHAR(50) NOT NULL,
    owner_id BIGINT NOT NULL,
    property_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    system_key VARCHAR(100),
    CONSTRAINT uk_financial_activities_name UNIQUE (name),
    CONSTRAINT uk_financial_activities_property UNIQUE (property_id),
    CONSTRAINT uk_financial_activities_system_key UNIQUE (system_key),
    CONSTRAINT fk_financial_activities_owner
        FOREIGN KEY (owner_id) REFERENCES household_members(id),
    CONSTRAINT fk_financial_activities_property
        FOREIGN KEY (property_id) REFERENCES properties(id)
);

INSERT INTO financial_activities
    (name, activity_type, tax_treatment, owner_id, property_id, active)
SELECT
    CASE
        WHEN LOWER(p.name) = 'needs classification' OR (
            SELECT COUNT(*)
            FROM properties duplicate_property
            WHERE LOWER(duplicate_property.name) = LOWER(p.name)
        ) > 1
        THEN p.name || ' (' || p.id || ')'
        ELSE p.name
    END,
    'RENTAL',
    'SCHEDULE_E',
    (SELECT MIN(id) FROM household_members),
    p.id,
    TRUE
FROM properties p;

