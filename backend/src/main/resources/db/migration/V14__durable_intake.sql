-- Fail closed before copying either legacy pending table. The source preflight reported no
-- duplicate identities, but the migration independently verifies the exact database it receives.
SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END
FROM (
    SELECT normalized.origin, normalized.source_id
    FROM (
        SELECT
            COALESCE(CAST(source_type AS VARCHAR), 'MANUAL') AS origin,
            source_id
        FROM pending_expenses
        WHERE source_id IS NOT NULL
        UNION ALL
        SELECT
            COALESCE(CAST(source_type AS VARCHAR), 'MANUAL') AS origin,
            source_id
        FROM pending_incomes
        WHERE source_id IS NOT NULL
    ) normalized
    GROUP BY normalized.origin, normalized.source_id
    HAVING COUNT(*) > 1
) duplicate_pending_identity;

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END
FROM (
