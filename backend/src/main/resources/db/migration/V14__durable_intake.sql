CREATE TABLE inbox_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin VARCHAR(50) NOT NULL,
    legacy_source_type VARCHAR(50),
    legacy_source_id VARCHAR(255),
    immutable_source_id VARCHAR(255),
    state VARCHAR(30) NOT NULL,
    external_sync_state VARCHAR(30) NOT NULL,
    proposed_direction VARCHAR(20),
    raw_status VARCHAR(50) NOT NULL,
    subject VARCHAR(1000),
    proposed_amount NUMERIC(38, 2),
    proposed_description VARCHAR(2000),
    proposed_date DATE,
    proposed_category VARCHAR(255),
    proposed_property_name VARCHAR(255),
    proposed_counterparty_name VARCHAR(255),
    proposed_source_label VARCHAR(500),
    legacy_activity_id BIGINT,
    legacy_category_id BIGINT,
    legacy_property_id BIGINT,
    legacy_counterparty_id BIGINT,
    configured_activity_id BIGINT,
    classification_ambiguous BOOLEAN NOT NULL,
    error_message VARCHAR(2000),
    receipt_external_id VARCHAR(255),
    receipt_file_name VARCHAR(500),
    financial_transaction_id BIGINT,
    migration_legacy_table VARCHAR(30),
    migration_legacy_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_inbox_items_origin_identity UNIQUE (origin, legacy_source_id),
    CONSTRAINT uk_inbox_items_migration_source
        UNIQUE (migration_legacy_table, migration_legacy_id),
    CONSTRAINT fk_inbox_items_financial_transaction
        FOREIGN KEY (financial_transaction_id) REFERENCES financial_transactions(id)
);

CREATE INDEX idx_inbox_items_state ON inbox_items(state);
CREATE INDEX idx_inbox_items_external_sync_state ON inbox_items(external_sync_state);
CREATE INDEX idx_inbox_items_created_at ON inbox_items(created_at);

CREATE TABLE inbox_artifacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_item_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    text_value VARCHAR(2000),
    external_id VARCHAR(255),
    file_name VARCHAR(500),
    sha256 VARCHAR(64),
    CONSTRAINT ck_inbox_artifacts_sha256
        CHECK (sha256 IS NULL OR CHAR_LENGTH(sha256) = 64),
    CONSTRAINT fk_inbox_artifacts_item
        FOREIGN KEY (inbox_item_id) REFERENCES inbox_items(id)
);

CREATE INDEX idx_inbox_artifacts_item ON inbox_artifacts(inbox_item_id);

CREATE TABLE legacy_inbox_map (
    legacy_table VARCHAR(30) NOT NULL,
    legacy_id BIGINT NOT NULL,
    inbox_item_id BIGINT NOT NULL,
    mapped_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_legacy_inbox_map PRIMARY KEY (legacy_table, legacy_id),
    CONSTRAINT fk_legacy_inbox_map_item
        FOREIGN KEY (inbox_item_id) REFERENCES inbox_items(id)
);

CREATE INDEX idx_legacy_inbox_map_item ON legacy_inbox_map(inbox_item_id);

CREATE TABLE background_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_item_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(500) NOT NULL,
    state VARCHAR(30) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 5,
    available_at TIMESTAMP(6) NOT NULL,
    lease_owner VARCHAR(255),
    lease_expires_at TIMESTAMP(6),
    last_error VARCHAR(2000),
    terminal_reason VARCHAR(100),
    legacy_pending_table VARCHAR(30),
    legacy_pending_id BIGINT,
    target_year INTEGER,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_background_jobs_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_background_jobs_attempts
        CHECK (attempts >= 0 AND max_attempts > 0 AND attempts <= max_attempts),
    CONSTRAINT ck_background_jobs_lease
        CHECK (
            (state = 'LEASED' AND lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)
            OR state <> 'LEASED'
        ),
    CONSTRAINT fk_background_jobs_item
        FOREIGN KEY (inbox_item_id) REFERENCES inbox_items(id)
);

CREATE INDEX idx_background_jobs_claim
    ON background_jobs(state, available_at, lease_expires_at);
CREATE INDEX idx_background_jobs_item ON background_jobs(inbox_item_id);

