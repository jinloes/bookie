    (SELECT COUNT(*) FROM inbox_items)
        = (SELECT COUNT(*) FROM pending_expenses) + (SELECT COUNT(*) FROM pending_incomes)
    AND (SELECT COUNT(*) FROM legacy_inbox_map)
