INSERT INTO legacy_transaction_map (
    legacy_table,
    legacy_id,
    transaction_id,
    legacy_expense_category,
    canonical_hash,
    mapped_at
)
SELECT
    transaction.migration_legacy_table,
    transaction.migration_legacy_id,
    transaction.id,
    legacy_expense.category,
    LOWER(
        RAWTOHEX(
            HASH(
                'SHA-256',
                STRINGTOUTF8(
                    'v2|' || transaction.migration_legacy_table
                    || '|' || CAST(transaction.migration_legacy_id AS VARCHAR)
                    || '|' || transaction.direction
                    || '|' || CAST(transaction.amount AS VARCHAR)
                    || '|' || CAST(transaction.transaction_date AS VARCHAR)
                    || '|' || CAST(CHAR_LENGTH(transaction.description) AS VARCHAR)
                    || ':' || transaction.description
                    || '|' || CAST(transaction.activity_id AS VARCHAR)
                    || '|' || CAST(transaction.neutral_category_id AS VARCHAR)
                    || '|' || COALESCE(CAST(transaction.counterparty_id AS VARCHAR), '')
                    || '|' || COALESCE(CAST(legacy_expense.category AS VARCHAR), '')
                    || '|' || COALESCE(import_reference.origin, '')
                    || '|' || CAST(CHAR_LENGTH(COALESCE(import_reference.external_id, '')) AS VARCHAR)
                    || ':' || COALESCE(import_reference.external_id, '')
                    || '|' || CAST(CHAR_LENGTH(COALESCE(import_reference.source_label, '')) AS VARCHAR)
                    || ':' || COALESCE(import_reference.source_label, '')
                    || '|' || COALESCE(attachment.storage_provider, '')
                    || '|' || CAST(CHAR_LENGTH(COALESCE(attachment.external_id, '')) AS VARCHAR)
                    || ':' || COALESCE(attachment.external_id, '')
                    || '|' || CAST(CHAR_LENGTH(COALESCE(attachment.file_name, '')) AS VARCHAR)
                    || ':' || COALESCE(attachment.file_name, '')
                    || '|' || COALESCE(attachment.sha256, '')
                )
            )
        )
    ),
    CURRENT_TIMESTAMP
FROM financial_transactions transaction
LEFT JOIN expenses legacy_expense
  ON transaction.migration_legacy_table = 'EXPENSES'
 AND transaction.migration_legacy_id = legacy_expense.id
LEFT JOIN transaction_import_references import_reference
  ON import_reference.transaction_id = transaction.id
LEFT JOIN transaction_attachments attachment
  ON attachment.transaction_id = transaction.id;

-- Every legacy row must have exactly one target and one durable mapping, with exact grouped totals.
SELECT 1 / CASE WHEN
    (SELECT COUNT(*) FROM financial_transactions)
        = (SELECT COUNT(*) FROM incomes) + (SELECT COUNT(*) FROM expenses)
    AND (SELECT COUNT(*) FROM legacy_transaction_map)
        = (SELECT COUNT(*) FROM incomes) + (SELECT COUNT(*) FROM expenses)
    AND (SELECT COUNT(*) FROM ledger_migration_quarantine) = 0
    AND (
        SELECT COALESCE(SUM(amount), 0)
        FROM financial_transactions
        WHERE direction = 'INCOME'
    ) = (SELECT COALESCE(SUM(amount), 0) FROM incomes)
    AND (
        SELECT COALESCE(SUM(amount), 0)
        FROM financial_transactions
        WHERE direction = 'EXPENSE'
    ) = (SELECT COALESCE(SUM(amount), 0) FROM expenses)
THEN 1 ELSE 0 END;

