-- Fail closed before creating the unified ledger. The migration copies every legacy financial
-- record; it never repairs, merges, or drops source rows.
SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END
FROM (
    SELECT id
    FROM incomes
    WHERE amount IS NULL
       OR amount <= 0
       OR date IS NULL
       OR description IS NULL
       OR activity_id IS NULL
       OR category_id IS NULL
    UNION ALL
    SELECT id
    FROM expenses
    WHERE amount IS NULL
       OR amount <= 0
       OR date IS NULL
       OR description IS NULL
       OR activity_id IS NULL
       OR category_id IS NULL
) invalid_financial_row;

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END
FROM (
    SELECT i.id
    FROM incomes i
    LEFT JOIN financial_activities activity ON activity.id = i.activity_id
    LEFT JOIN financial_categories category ON category.id = i.category_id
    LEFT JOIN legacy_category_map category_map
      ON category_map.legacy_category_id = i.category_id
    LEFT JOIN legacy_payer_map payer_map ON payer_map.payer_id = i.payer_id
    WHERE activity.id IS NULL
       OR category.id IS NULL
       OR category.direction <> 'INCOME'
       OR category_map.legacy_category_id IS NULL
       OR (i.payer_id IS NOT NULL AND payer_map.payer_id IS NULL)
       OR i.property_id IS DISTINCT FROM activity.property_id
    UNION ALL
    SELECT e.id
    FROM expenses e
    LEFT JOIN financial_activities activity ON activity.id = e.activity_id
    LEFT JOIN financial_categories category ON category.id = e.category_id
    LEFT JOIN legacy_category_map category_map
      ON category_map.legacy_category_id = e.category_id
    LEFT JOIN legacy_payer_map payer_map ON payer_map.payer_id = e.payer_id
    WHERE activity.id IS NULL
       OR category.id IS NULL
       OR category.direction <> 'EXPENSE'
       OR category_map.legacy_category_id IS NULL
       OR (e.payer_id IS NOT NULL AND payer_map.payer_id IS NULL)
       OR e.property_id IS DISTINCT FROM activity.property_id
) unmappable_financial_row;

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END
FROM (
    SELECT normalized_source.origin, normalized_source.external_id
    FROM (
        SELECT
            COALESCE(CAST(source_type AS VARCHAR), 'MANUAL') AS origin,
            source_id AS external_id
        FROM incomes
        WHERE source_id IS NOT NULL
        UNION ALL
        SELECT
            COALESCE(CAST(source_type AS VARCHAR), 'MANUAL') AS origin,
            source_id AS external_id
        FROM expenses
        WHERE source_id IS NOT NULL
    ) normalized_source
    GROUP BY normalized_source.origin, normalized_source.external_id
    HAVING COUNT(*) > 1
) duplicate_source_identity;

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END
FROM (
    SELECT receipt_one_drive_id
    FROM (
        SELECT receipt_one_drive_id FROM incomes
        UNION ALL
        SELECT receipt_one_drive_id FROM expenses
    ) receipt_identity
    WHERE receipt_one_drive_id IS NOT NULL
    GROUP BY receipt_one_drive_id
    HAVING COUNT(*) > 1
) duplicate_attachment_identity;

CREATE TABLE financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2) NOT NULL,
    direction ENUM('INCOME', 'EXPENSE') NOT NULL,
    transaction_date DATE NOT NULL,
    description VARCHAR(2000) NOT NULL,
    activity_id BIGINT NOT NULL,
    neutral_category_id BIGINT NOT NULL,
    counterparty_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP(6),
    migration_legacy_table VARCHAR(20),
    migration_legacy_id BIGINT,
    CONSTRAINT ck_financial_transactions_amount CHECK (amount > 0),
    CONSTRAINT uk_financial_transactions_migration_source
        UNIQUE (migration_legacy_table, migration_legacy_id),
    CONSTRAINT fk_financial_transactions_activity
        FOREIGN KEY (activity_id) REFERENCES financial_activities(id),
    CONSTRAINT fk_financial_transactions_neutral_category
        FOREIGN KEY (neutral_category_id) REFERENCES neutral_categories(id),
    CONSTRAINT fk_financial_transactions_counterparty
        FOREIGN KEY (counterparty_id) REFERENCES counterparties(id)
);

CREATE TABLE transaction_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    storage_provider VARCHAR(50) NOT NULL,
    external_id VARCHAR(255),
    file_name VARCHAR(500),
    sha256 VARCHAR(64),
    CONSTRAINT ck_transaction_attachments_identity
        CHECK (external_id IS NOT NULL OR file_name IS NOT NULL OR sha256 IS NOT NULL),
    CONSTRAINT uk_transaction_attachments_external
        UNIQUE (storage_provider, external_id),
    CONSTRAINT fk_transaction_attachments_transaction
        FOREIGN KEY (transaction_id) REFERENCES financial_transactions(id)
);

CREATE TABLE transaction_import_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    origin VARCHAR(50) NOT NULL,
    external_id VARCHAR(255),
    source_label VARCHAR(500),
    CONSTRAINT uk_transaction_import_references_external
        UNIQUE (origin, external_id),
    CONSTRAINT fk_transaction_import_references_transaction
        FOREIGN KEY (transaction_id) REFERENCES financial_transactions(id)
);

CREATE TABLE legacy_transaction_map (
    legacy_table ENUM('INCOMES', 'EXPENSES') NOT NULL,
    legacy_id BIGINT NOT NULL,
    transaction_id BIGINT NOT NULL,
    legacy_expense_category ENUM(
        'ADVERTISING',
        'AUTO_AND_TRAVEL',
        'CLEANING_AND_MAINTENANCE',
        'COMMISSIONS',
        'DEPRECIATION',
        'INSURANCE',
        'LEGAL_AND_PROFESSIONAL',
        'MANAGEMENT_FEES',
        'MORTGAGE_INTEREST',
        'OTHER',
        'OTHER_INTEREST',
        'REPAIRS',
        'SUPPLIES',
        'TAXES',
        'UTILITIES'
    ),
    canonical_hash VARCHAR(64) NOT NULL,
    mapped_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_legacy_transaction_map PRIMARY KEY (legacy_table, legacy_id),
    CONSTRAINT uk_legacy_transaction_map_transaction UNIQUE (transaction_id),
    CONSTRAINT ck_legacy_transaction_map_expense_category
        CHECK (legacy_table = 'EXPENSES' OR legacy_expense_category IS NULL),
    CONSTRAINT ck_legacy_transaction_map_hash
        CHECK (CHAR_LENGTH(canonical_hash) = 64),
    CONSTRAINT fk_legacy_transaction_map_transaction
        FOREIGN KEY (transaction_id) REFERENCES financial_transactions(id)
);

CREATE TABLE ledger_migration_quarantine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_table VARCHAR(20) NOT NULL,
    legacy_id BIGINT NOT NULL,
    reason VARCHAR(100) NOT NULL,
    salted_identity_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ledger_migration_quarantine_legacy
        UNIQUE (legacy_table, legacy_id),
    CONSTRAINT ck_ledger_migration_quarantine_hash
        CHECK (CHAR_LENGTH(salted_identity_hash) = 64)
);

