UPDATE incomes i
SET category_id = (
    SELECT fc.id
    FROM financial_categories fc
    WHERE fc.category_key = CASE
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = i.activity_id
        ) = 'SCHEDULE_E' THEN 'RENTAL_INCOME'
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = i.activity_id
        ) = 'W2' THEN 'WAGES'
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = i.activity_id
        ) = 'SCHEDULE_C' THEN 'SERVICE_INCOME'
        ELSE 'OTHER_INCOME'
    END
);

UPDATE expenses e
SET category_id = (
    SELECT fc.id
    FROM financial_categories fc
    WHERE fc.category_key = CASE
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = e.activity_id
        ) = 'SCHEDULE_E' THEN COALESCE(CAST(e.category AS VARCHAR), 'OTHER')
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = e.activity_id
        ) = 'W2' THEN 'EMPLOYMENT_OTHER_EXPENSE'
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = e.activity_id
        ) = 'SCHEDULE_C' THEN 'SCHEDULE_C_OTHER_EXPENSE'
        ELSE 'OTHER_EXPENSE'
    END
);

UPDATE expenses
SET category_id = (SELECT id FROM financial_categories WHERE category_key = 'OTHER_EXPENSE')
WHERE category_id IS NULL;

