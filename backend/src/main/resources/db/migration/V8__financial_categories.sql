    tax_line VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    system BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_financial_categories_key UNIQUE (category_key)
);

