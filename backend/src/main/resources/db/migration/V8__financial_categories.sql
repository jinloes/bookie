UPDATE pending_expenses pe
SET category_id = (
    SELECT fc.id
    FROM financial_categories fc
    WHERE fc.category_key = CASE
        WHEN pe.email_type = 'INCOME' AND (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'SCHEDULE_E' THEN 'RENTAL_INCOME'
        WHEN pe.email_type = 'INCOME' AND (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'W2' THEN 'WAGES'
        WHEN pe.email_type = 'INCOME' AND (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'SCHEDULE_C' THEN 'SERVICE_INCOME'
        WHEN pe.email_type = 'INCOME' THEN 'OTHER_INCOME'
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'SCHEDULE_E' AND EXISTS (
            SELECT 1
            FROM financial_categories suggested
            WHERE suggested.category_key = pe.category
              AND suggested.direction = 'EXPENSE'
              AND suggested.tax_treatment = 'SCHEDULE_E'
        ) THEN pe.category
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'SCHEDULE_E' THEN 'OTHER'
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'W2' THEN 'EMPLOYMENT_OTHER_EXPENSE'
        WHEN (
            SELECT fa.tax_treatment
            FROM financial_activities fa
            WHERE fa.id = pe.activity_id
        ) = 'SCHEDULE_C' THEN 'SCHEDULE_C_OTHER_EXPENSE'
        ELSE 'OTHER_EXPENSE'
    END
);

UPDATE pending_expenses pe
SET category_id = (
    SELECT id
    FROM financial_categories
    WHERE category_key = CASE
        WHEN pe.email_type = 'INCOME' THEN 'OTHER_INCOME'
        ELSE 'OTHER_EXPENSE'
    END
)
WHERE category_id IS NULL;

