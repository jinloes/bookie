package com.bookie.datalifecycle.portable;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.Locale;

/** H2 (the local desktop database) operations. */
class H2VendorOperations implements DatabaseVendorOperations {

  @Override
  public String vendor() {
    return H2;
  }

  @Override
  public String schema() {
    return "PUBLIC";
  }

  @Override
  public String physicalName(String logicalName) {
    return logicalName.toUpperCase(Locale.ROOT);
  }

  @Override
  public void beginSnapshot(Connection connection) throws SQLException {
    connection.setAutoCommit(false);
    connection.setTransactionIsolation(Connection.TRANSACTION_REPEATABLE_READ);
  }

  // SET REFERENTIAL_INTEGRITY commits the open transaction, so imports rely on inserting in
  // foreign-key order instead; the Bookie foreign-key graph is acyclic.
  @Override
  public void disableConstraints(Connection connection, List<String> tables) {}

  @Override
  public void enableConstraints(Connection connection, List<String> tables) {}

  // H2 identity columns are GENERATED BY DEFAULT and accept explicit values.
  @Override
  public void setIdentityInsert(Connection connection, String table, boolean enabled) {}

  @Override
  public void reseed(Connection connection, String table, String column, long floor)
      throws SQLException {
    try (Statement statement = connection.createStatement()) {
      statement.execute(
          "ALTER TABLE "
              + qualified(table)
              + " ALTER COLUMN "
              + quote(column)
              + " RESTART WITH "
              + (floor + 1));
    }
  }
}
