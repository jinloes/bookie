class H2VendorOperationsTest {

  private final H2VendorOperations vendor = new H2VendorOperations();
  private Connection connection;

  @BeforeEach
  void setUp() throws Exception {
    connection =
        DriverManager.getConnection(
            "jdbc:h2:mem:vendor_" + UUID.randomUUID().toString().replace("-", ""), "sa", "");
  }

  @AfterEach
  void tearDown() throws Exception {
    connection.close();
  }

  private void execute(String sql) throws Exception {
    try (Statement statement = connection.createStatement()) {
      statement.execute(sql);
    }
  }

  @Nested
  class Naming {

    @Test
    void usesUpperCaseNamesInThePublicSchema() {
      assertThat(vendor.vendor()).isEqualTo("h2");
      assertThat(vendor.schema()).isEqualTo("PUBLIC");
      assertThat(vendor.physicalName("financial_transactions")).isEqualTo("FINANCIAL_TRANSACTIONS");
      assertThat(vendor.quote("a\"b")).isEqualTo("\"A\"\"B\"");
      assertThat(vendor.qualified("items")).isEqualTo("\"PUBLIC\".\"ITEMS\"");
    }
  }

  @Nested
  class Of {

    private Connection product(String name) throws Exception {
      Connection mocked = mock(Connection.class);
      DatabaseMetaData metadata = mock(DatabaseMetaData.class);
      when(mocked.getMetaData()).thenReturn(metadata);
      when(metadata.getDatabaseProductName()).thenReturn(name);
      return mocked;
    }

    @Test
    void picksTheVendorFromTheProductName() throws Exception {
      assertThat(DatabaseVendorOperations.of(connection)).isInstanceOf(H2VendorOperations.class);
      assertThat(DatabaseVendorOperations.of(product("Microsoft SQL Server")))
          .isInstanceOf(SqlServerVendorOperations.class);
    }

    @Test
    void rejectsAnUnsupportedDatabase() throws Exception {
      Connection postgres = product("PostgreSQL");

      assertThatThrownBy(() -> DatabaseVendorOperations.of(postgres))
          .isInstanceOf(IllegalStateException.class)
          .hasMessage("Unsupported database: POSTGRESQL");
    }
  }

  @Nested
  class BeginSnapshot {

    @Test
    void startsARepeatableReadTransaction() throws Exception {
      vendor.beginSnapshot(connection);

      assertThat(connection.getAutoCommit()).isFalse();
      assertThat(connection.getTransactionIsolation())
          .isEqualTo(Connection.TRANSACTION_REPEATABLE_READ);
    }
  }

  @Nested
  class SqlServerBeginSnapshot {

    @Test
    void rejectsADatabaseMissingFromSysDatabases() throws Exception {
      Connection mocked = mock(Connection.class);
      Statement statement = mock(Statement.class);
      ResultSet result = mock(ResultSet.class);
      when(mocked.createStatement()).thenReturn(statement);
      when(statement.executeQuery(anyString())).thenReturn(result);
      when(result.next()).thenReturn(false);
      SqlServerVendorOperations sqlServer = new SqlServerVendorOperations();

      assertThatThrownBy(() -> sqlServer.beginSnapshot(mocked))
          .isInstanceOf(IllegalStateException.class)
          .hasMessageStartingWith("Snapshot isolation is off for this database.");
      verify(mocked, never()).setAutoCommit(anyBoolean());
    }
  }

  @Nested
  class BookieTables {

    @Test
    void listsBookieTablesInForeignKeyOrderWithColumnMetadata() throws Exception {
      execute("CREATE TABLE zeta (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
      execute(
          """
          CREATE TABLE alpha (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              zeta_id BIGINT REFERENCES zeta (id),
              parent_id BIGINT REFERENCES alpha (id),
              amount DECIMAL(10, 2),
              doubled DECIMAL(10, 2) GENERATED ALWAYS AS (amount * 2),
              kind ENUM('A', 'B')
          )
          """);
      execute("CREATE TABLE jobrunr_jobs (id VARCHAR(36) PRIMARY KEY)");
      execute(
          """
          CREATE TABLE beta (
              alpha_id BIGINT REFERENCES alpha (id),
              job_id VARCHAR(36) REFERENCES jobrunr_jobs (id),
              note VARCHAR(10)
          )
          """);
      execute("CREATE TABLE flyway_schema_history (installed_rank INT)");
      execute("CREATE TABLE event_publication (id UUID)");

      List<TableMetadata> tables = vendor.bookieTables(connection);

      assertThat(tables).extracting(TableMetadata::name).containsExactly("ZETA", "ALPHA", "BETA");
      TableMetadata alpha = tables.get(1);
      assertThat(alpha.parents()).containsExactly("ZETA");
      assertThat(alpha.columns())
          .containsExactly(
              new ColumnMetadata("ID", "INTEGER", Types.BIGINT, true, false),
              new ColumnMetadata("ZETA_ID", "INTEGER", Types.BIGINT, false, false),
              new ColumnMetadata("PARENT_ID", "INTEGER", Types.BIGINT, false, false),
              new ColumnMetadata("AMOUNT", "DECIMAL", Types.DECIMAL, false, false),
              new ColumnMetadata("DOUBLED", "DECIMAL", Types.DECIMAL, false, true),
              new ColumnMetadata("KIND", "STRING", Types.OTHER, false, false));
      assertThat(alpha.insertableColumns())
          .extracting(ColumnMetadata::name)
          .doesNotContain("DOUBLED");
      assertThat(alpha.identityColumn().name()).isEqualTo("ID");
      assertThat(tables.get(2).parents()).containsExactly("ALPHA");
      assertThat(tables.get(2).identityColumn()).isNull();
    }

    @Test
    void rejectsForeignKeyCycles() throws Exception {
      execute("CREATE TABLE a (id INT PRIMARY KEY, b_id INT)");
      execute("CREATE TABLE b (id INT PRIMARY KEY, a_id INT REFERENCES a (id))");
      execute("ALTER TABLE a ADD FOREIGN KEY (b_id) REFERENCES b (id)");

      assertThatThrownBy(() -> vendor.bookieTables(connection))
          .isInstanceOf(IllegalStateException.class)
          .hasMessage("Foreign keys between Bookie tables form a cycle");
    }
  }

  @Nested
  class Writes {

    @Test
    void constraintAndIdentityTogglesAreNoOps() throws Exception {
      execute("CREATE TABLE items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
      connection.setAutoCommit(false);

      vendor.disableConstraints(connection, List.of("ITEMS"));
      vendor.setIdentityInsert(connection, "ITEMS", true);
      execute("INSERT INTO items (id) VALUES (5)");
      vendor.setIdentityInsert(connection, "ITEMS", false);
      vendor.enableConstraints(connection, List.of("ITEMS"));
      connection.commit();

      assertThat(vendor.bookieTables(connection)).hasSize(1);
    }

    @Test
    void reseedsSoTheNextIdIsAboveTheFloor() throws Exception {
      execute("CREATE TABLE items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n INT)");

      vendor.reseed(connection, "ITEMS", "ID", 41);
      execute("INSERT INTO items (n) VALUES (1)");

      try (Statement statement = connection.createStatement();
          ResultSet result = statement.executeQuery("SELECT id FROM items")) {
        result.next();
        assertThat(result.getLong(1)).isEqualTo(42);
      }
    }
  }

  @Nested
  class TypeFamily {

    @ParameterizedTest
    @CsvSource({
      "1111, UUID, UUID",
      "1, uniqueidentifier, UUID",
      "1111, ENUM('A'), STRING",
      "-5, BIGINT, INTEGER",
      "4, INT, INTEGER",
      "5, SMALLINT, INTEGER",
      "-6, TINYINT, INTEGER",
      "3, DECIMAL, DECIMAL",
      "2, NUMERIC, DECIMAL",
      "16, BOOLEAN, BOOLEAN",
      "-7, bit, BOOLEAN",
      "1, CHAR, STRING",
      "12, VARCHAR, STRING",
      "-15, NCHAR, STRING",
      "-9, NVARCHAR, STRING",
      "-1, LONGVARCHAR, STRING",
      "-16, LONGNVARCHAR, STRING",
      "2005, CLOB, STRING",
      "2011, NCLOB, STRING",
      "-2, BINARY, BINARY",
      "-3, VARBINARY, BINARY",
      "-4, LONGVARBINARY, BINARY",
      "2004, BLOB, BINARY",
      "8, DOUBLE, FLOAT",
      "6, FLOAT, FLOAT",
      "7, REAL, FLOAT",
      "91, DATE, DATE",
      "92, TIME, TIME",
      "93, TIMESTAMP, TIMESTAMP",
      "2014, TIMESTAMP WITH TIME ZONE, TIMESTAMP_TZ",
      "-155, datetimeoffset, TIMESTAMP_TZ",
      "2003, ARRAY, OTHER:ARRAY"
    })
    void mapsJdbcTypesToVendorNeutralFamilies(int jdbcType, String typeName, String family) {
      assertThat(DatabaseVendorOperations.typeFamily(jdbcType, typeName)).isEqualTo(family);
    }

    @Test
    void treatsAMissingTypeNameAsEmpty() {
      assertThat(DatabaseVendorOperations.typeFamily(Types.OTHER, null)).isEqualTo("OTHER:");
    }
  }

  @Nested
  class IsBookieTable {

    @Test
    void excludesEngineAndHistoryTables() {
      assertThat(
              Set.of("FLYWAY_SCHEMA_HISTORY", "EVENT_PUBLICATION", "JOBRUNR_JOBS", "PROPERTIES")
                  .stream()
                  .filter(DatabaseVendorOperations::isBookieTable))
          .containsExactly("PROPERTIES");
    }
  }
}
